#!/usr/bin/env python3
# Bakes the spinner's sub into hooks/icons.ts as braille, three rows tall (a cell is two dots wide, four tall). Drawn by hand dot by
# dot: font glyphs fitted to this size lose what they are.
#   python3 helm-spinner/tools/bake-icons.py
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "hooks", "icons.ts")
DOTS = [[0x01, 0x08], [0x02, 0x10], [0x04, 0x20], [0x40, 0x80]]

ICONS = {
    # Faces right, toward the sound wave it sends out beside it: propeller, long hull with portholes, tower, periscope.
    "sub": [
        "............###.........",
        "............#...........",
        "............#...........",
        ".........#######........",
        ".........#######........",
        "......##############....",
        ".#..##################..",
        "##.#####..###..###..###.",
        "##.#####..###..###..###.",
        ".#..##################..",
        "......##############....",
        "........................",
    ],
}


def braille(dots):
    rows = []
    for r in range(len(dots) // 4):
        line = ""
        for c in range(len(dots[0]) // 2):
            bits = 0
            for y in range(4):
                for x in range(2):
                    if dots[r * 4 + y][c * 2 + x] == "#":
                        bits |= DOTS[y][x]
            line += chr(0x2800 + bits)
        rows.append(line)
    return rows


def paint(dots, at, mark="#"):
    """Sets some dots, or clears them with mark='.'."""
    rows = [list(row) for row in dots]
    for x, y in at:
        rows[y][x] = mark
    return ["".join(row) for row in rows]


def frames_of(name):
    """What each icon does: the same drawing, moving."""
    base = ICONS[name]
    if name == "sub":  # the propeller turning, bubbles rising off it and wobbling up past the hull
        spun = paint(base, [(0, 7), (0, 8), (1, 6), (1, 9)], ".")
        steps = 6
        frames = []
        for step in range(steps):
            dots = base if step % 2 == 0 else spun
            for start, col, big in ((0, 3, False), (2, 6, True), (4, 1, False)):
                age = (step + start) % steps
                y, x = 5 - age, col + (age % 2)
                if big and age > 1:  # the big one swells as it rises
                    dots = paint(dots, [(x, y), (x + 1, y), (x, y - 1 if y else y), (x + 1, y - 1 if y else y)])
                else:
                    dots = paint(dots, [(x, y)])
            frames.append(dots)
        return frames
    return [base]


lines = ["// Generated by tools/bake-icons.py, drawn by hand: don't edit, re-bake. The sub's frames, each three rows of braille.", "export const ICON_ART: Record<string, string[][]> = {"]
for name, dots in ICONS.items():
    assert len(dots) == 12 and len({len(row) for row in dots}) == 1, name
    frames = [braille(frame) for frame in frames_of(name)]
    print(name, len(frames))
    for rows in zip(*frames):
        print("   ".join(rows))
    lines.append(f"  '{name}': {frames!r},".replace('"', "'"))
lines.append("}")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
